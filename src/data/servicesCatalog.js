export function getCategoryBySlug(slug) {
  if (!slug) return CATEGORIES_CATALOG[0]
  const clean = slug.toLowerCase()
  const exact = CATEGORIES_CATALOG.find((c) => c.slug === clean || c.id === clean)
  if (exact) return exact
  if (clean.includes("ac") || clean.includes("cool")) return CATEGORIES_CATALOG[0]
  if (clean.includes("wir") || clean.includes("mcb") || clean.includes("switch") || clean.includes("elec")) return CATEGORIES_CATALOG[1]
  if (clean.includes("fan") || clean.includes("motor") || clean.includes("geyser") || clean.includes("pump")) return CATEGORIES_CATALOG[2]
  if (clean.includes("fridge") || clean.includes("wash") || clean.includes("ro") || clean.includes("tv") || clean.includes("app")) return CATEGORIES_CATALOG[3]
  if (clean.includes("plumb") || clean.includes("tap") || clean.includes("tank") || clean.includes("water")) return CATEGORIES_CATALOG[4]
  if (clean.includes("clean") || clean.includes("pest") || clean.includes("sofa")) return CATEGORIES_CATALOG[5]
  if (clean.includes("carp") || clean.includes("drill") || clean.includes("door") || clean.includes("lock")) return CATEGORIES_CATALOG[6]
  if (clean.includes("cctv") || clean.includes("smart") || clean.includes("cam")) return CATEGORIES_CATALOG[7]
  return CATEGORIES_CATALOG[0]
}

